#!/usr/bin/env python3
"""Read-only source completeness audit for H1 Bayesian information value.

Original source rows are NOT copied into this artifact. This matrix is a
curated study-level discovery ledger, not a comprehensive systematic review.
"""
import csv
import json
from collections import Counter
from pathlib import Path

ROOT=Path(__file__).resolve().parent

def audit():
    with (ROOT/"H1_TWO_CHANNEL_SOURCE_ELIGIBILITY_V1.csv").open(newline="",encoding="utf-8") as f:
        rows=list(csv.DictReader(f))
    assert len(rows)==7
    assert len({r["case_id"] for r in rows})==len(rows)
    assert all(r["source_doi"] and r["cue_channel"] and r["region"] for r in rows)
    assert all(r["identifies_bayesian_VOI"] in ("yes","no") for r in rows)
    assert all(r["private_and_social_in_same_bats"] in ("yes","no","unknown") for r in rows)
    controls=Counter(r["cue_control"] for r in rows)
    channels=Counter(r["cue_channel"] for r in rows)
    min_names=("resource_available_prior","memory_navigation_success",
               "resource_cue_sensitivity","resource_cue_false_positive",
               "travel_cost_measured","cue_cost_measured")
    complete=sum(all(r[k] not in ("NA","unknown","") for k in min_names) for r in rows)
    return {
      "status":"SOURCE_ELIGIBILITY_ONLY_NO_H1_EFFECT_FIT",
      "source_cases":len(rows),
      "source_region_labels":len({r["region"] for r in rows}),
      "original_source_groups_with_all_required_direct_parameters":complete,
      "original_source_groups_claimed_identified_VOI":sum(r["identifies_bayesian_VOI"]=="yes" for r in rows),
      "group_with_direct_individual_memory_and_social_CUE":sum(r["private_and_social_in_same_bats"]=="yes" for r in rows),
      "cue_channel_counts":dict(sorted(channels.items())),
      "cue_control_counts":dict(sorted(controls.items())),
      "selected_responder_studies":sum(r["observation_or_response_selection"]=="responder_only" for r in rows),
      "not_systematic_review":True,
      "model_2019_buzz_pre_exact_external_replicates":0,
      "model_globally_identified":False,
      "falsifiable_next_data":"independent place-memory probability, prior food availability, cue sensitivity/FPR, visit reward/cost and group IDs in same population",
      "claim":"the presence of distinct sources does not prove a shared causal predictor, receiver-payoff or private-memory trait"
    }

def main():
    out=audit()
    print(json.dumps(out,indent=2,ensure_ascii=False))
    p=ROOT/"H1_TWO_CHANNEL_SOURCE_GATE_V1.json"
    # Artifact is generated by CI to /tmp instead of writing to source branch.
if __name__=="__main__":
    main()
